import { pathToFileURL } from "node:url";
import { mkdir } from "node:fs/promises";
import assert from "node:assert/strict";
const { chromium } = await import(process.env.PLAYWRIGHT_CORE ? pathToFileURL(process.env.PLAYWRIGHT_CORE).href : "playwright-core");
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM, headless: true, args: ["--use-angle=swiftshader", "--enable-unsafe-swiftshader"] });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
page.on("pageerror", error => errors.push(String(error)));
const base = process.env.HANGAR_URL || "http://127.0.0.1:8003";
const output = "var/fleet-qa";
await mkdir(output, { recursive: true });
try {
  await page.goto(`${base}/#world`, { waitUntil: "domcontentloaded", timeout: 90000 });
  await page.getByRole("heading", { name: "A world of work." }).waitFor({ timeout: 90000 });
  const frameElement = page.locator('iframe[title^="Hangar project world"]');
  await frameElement.waitFor({ timeout: 60000 });
  const frame = await (await frameElement.elementHandle()).contentFrame();
  await frame.waitForFunction(() => !!window.atlas, { timeout: 60000 });
  await page.waitForTimeout(2500);
  await page.screenshot({ path: `${output}/world-desktop.png`, fullPage: true });
  assert.ok(await frame.evaluate(() => window.atlas.buildings.length) > 0);
  await page.getByRole("button", { name: "Projects", exact: true }).click();
  await page.getByRole("heading", { name: "Your projects." }).waitFor();
  await page.getByRole("searchbox", { name: "Find a project" }).filter({ visible: true }).fill("hangar");
  await page.locator(".cw-project-tile").filter({ hasText: "hangar" }).first().click();
  await page.getByRole("heading", { name: "hangar", exact: true }).waitFor();
  await page.getByRole("button", { name: "Start a coding task" }).click();
  await page.getByRole("dialog").waitFor();
  await page.getByRole("textbox", { name: "What do you want done?" }).fill("Inspect this project and report what needs doing. Do not modify files.");
  assert.equal(await page.getByRole("button", { name: /^Run on/ }).isEnabled(), true);
  await page.keyboard.press("Escape");
  await page.getByRole("button", { name: "Sessions", exact: true }).click();
  await page.getByRole("heading", { name: "Session history", exact: true }).waitFor();
  await page.locator(".cw-session-row").first().waitFor({ timeout: 90000 });
  await page.screenshot({ path: `${output}/sessions-desktop.png`, fullPage: false });
  await page.getByRole("button", { name: "Continue", exact: true }).and(page.locator(":enabled")).first().click();
  await page.getByRole("heading", { name: "Continue the work." }).waitFor();
  await page.keyboard.press("Escape");
  await page.getByRole("button", { name: "Machines", exact: true }).click();
  await page.getByRole("heading", { name: "Connect through SSH." }).waitFor();
  assert.equal(await page.locator("select:visible").count(), 0);
  await page.screenshot({ path: `${output}/machines-desktop.png`, fullPage: true });
  await page.getByRole("button", { name: "Models", exact: true }).click();
  await page.getByRole("heading", { name: "Intelligence, wherever it runs." }).waitFor();
  await page.locator(".cw-model-tile").first().waitFor({ timeout: 60000 });
  await page.screenshot({ path: `${output}/models-desktop.png`, fullPage: true });
  await page.getByRole("button", { name: "World", exact: true }).click();
  await page.getByRole("button", { name: "Close project", exact: true }).click();
  for (const width of [390, 320]) {
    await page.setViewportSize({ width, height: 844 });
    await page.waitForTimeout(500);
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), `horizontal overflow at ${width}`);
    await page.screenshot({ path: `${output}/world-${width}.png`, fullPage: true });
  }
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.getByRole("button", { name: "Switch to light mode" }).click();
  await page.waitForTimeout(1000);
  await page.screenshot({ path: `${output}/world-light.png`, fullPage: true });
  assert.deepEqual(errors, []);
  console.log("PASS: real Hangar world, project selection, composer, session continuation, machines, models, 320/390/1440 layouts and light mode; no browser errors.");
} finally { await browser.close(); }
